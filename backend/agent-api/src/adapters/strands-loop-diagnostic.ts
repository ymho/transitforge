import type { Message, ToolResultBlock } from "@strands-agents/sdk";
import { ConditionUpdateRejectedError } from "@raiquora/agent/conversation-condition";

const errorCodes = new Set(["invalid_input", "precondition_failed", "unknown_tool", "not_found", "outside_coverage", "precondition_missing", "stale_revision", "permission_denied", "rate_limited", "unavailable", "ambiguous_entity", "execution_failed", "intent_unavailable", "tool_budget"]);
const issueCodes = new Set(["invalid_type", "too_big", "too_small", "invalid_format", "not_multiple_of", "unrecognized_keys", "invalid_union", "invalid_key", "invalid_element", "invalid_value", "custom"]);
export function strandsModelDiagnostic(message: Message | undefined, knownTools: ReadonlySet<string>): Record<string, unknown> {
  if (!message) return {};
  const content = message.content;
  const numbers: Record<string, number> = {};
  for (const key of ["inputTokens", "outputTokens", "totalTokens"] as const) {
    const value = message.metadata?.usage?.[key];
    if (typeof value === "number" && Number.isSafeInteger(value) && value >= 0 && value <= 20_000_000) numbers[key] = value;
  }
  return { ...numbers, textBlocks: content.filter(block => block.type === "textBlock").length,
    reasoningBlocks: content.filter(block => block.type === "reasoningBlock").length,
    toolBlocks: content.filter(block => block.type === "toolUseBlock").length,
    tools: content.filter(block => block.type === "toolUseBlock").slice(0, 32)
      .map(block => block.type === "toolUseBlock" && knownTools.has(block.name) ? block.name : "unknown_tool") };
}
/** SDK success can carry an Application rejection (ok:false). Inspect only its closed code. */
export function strandsToolDiagnostic(result: ToolResultBlock): Record<string, unknown> {
  if (result.error instanceof ConditionUpdateRejectedError) return { outcome: "rejected", code: result.error.code };
  // This exact prefix is generated by the adapter, never copied to diagnostics.
  if (result.error?.message.startsWith("invalid_source: No condition was changed.")) return { outcome: "rejected", code: "invalid_source" };
  const issues = result.error && "issues" in result.error ? (result.error as { issues?: unknown }).issues : undefined;
  if (Array.isArray(issues)) return { outcome: "rejected", code: "schema_invalid",
    issues: [...new Set(issues.slice(0, 32).flatMap(issue => issue && typeof issue === "object" &&
      typeof issue.code === "string" && issueCodes.has(issue.code) ? [issue.code] : ["unclassified"]))] };
  for (const block of result.content) {
    let payload: unknown = block.type === "jsonBlock" ? block.json : undefined;
    if (block.type === "textBlock" && block.text.startsWith("{") && block.text.length <= 1_000_000) {
      try { payload = JSON.parse(block.text); } catch { /* Not an Application JSON result. */ }
    }
    if (!payload || typeof payload !== "object" || !("ok" in payload) || payload.ok !== false) continue;
    const error = "error" in payload && payload.error && typeof payload.error === "object" ? payload.error : undefined;
    const code = error && "code" in error && typeof error.code === "string" && errorCodes.has(error.code) ? error.code : "unclassified";
    return { outcome: "rejected", code };
  }
  return { outcome: result.status === "error" ? "failed" : "completed" };
}
